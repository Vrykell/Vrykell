import { expect, test } from '@playwright/test';
import { setupTauriMock, ensureTabsOpen } from './tauri-mock';
import { gotoSetting } from './settings';

for (const theme of ['深色', '浅色']) {
  test(`saved SSH colors supply terminal defaults and preserve explicit overrides in ${theme}`, async ({ page }, testInfo) => {
    await setupTauriMock(page, { schedulesSeed: [] });
    await page.goto('/');
    await gotoSetting(page, '主题');
    await page.getByRole('radio', { name: theme, exact: true }).click();
    await page.locator('[data-dock-btn="ssh"]').click();
    const connection = page.getByTestId('ssh-row-ssh-1');
    const connectionIcon = connection.locator('.sidebar-row-icon svg');
    const original = await connectionIcon.evaluate(element => getComputedStyle(element).color);
    await connection.click({ button: 'right' });
    await page.getByRole('menuitemradio', { name: '紫色', exact: true }).click();
    const selected = await connectionIcon.evaluate(element => getComputedStyle(element).color);
    expect(selected).not.toBe(original);
    await connection.click({ button: 'right' });
    await page.screenshot({ path: testInfo.outputPath('ssh-color-menu.png'), animations: 'disabled' });
    await page.keyboard.press('Escape');
    await connection.dblclick();
    await ensureTabsOpen(page);
    const tab = page.locator('[data-tab-kind="session"]').filter({ hasText: '生产服务器' });
    const tabIcon = tab.locator('[role="tab"] svg');
    await expect(tabIcon).toHaveCSS('color', selected);
    await page.locator('[data-dock-btn="ssh"]').click();
    await page.locator('[data-dock-btn="chat"]').click();
    await page.getByRole('button', { name: '会话设置', exact: true }).click();
    const target = page.getByTestId('chat-execution-target');
    await target.click();
    const option = page.getByRole('option').filter({ hasText: '生产服务器' });
    await expect(option.locator('.ui-select-swatch')).toHaveCSS('background-color', selected);
    await option.click();
    await expect(target.locator('.ui-select-swatch')).toHaveCSS('background-color', selected);
    await page.locator('[data-dock-btn="chat"]').click();
    await ensureTabsOpen(page);
    await tab.click({ button: 'right' });
    await page.getByRole('menuitemradio', { name: '蓝色', exact: true }).click();
    const explicit = await tabIcon.evaluate(element => getComputedStyle(element).color);
    await page.locator('[data-dock-btn="ssh"]').click();
    await connection.click({ button: 'right' });
    await page.getByRole('menuitemradio', { name: '绿色', exact: true }).click();
    const inherited = await connectionIcon.evaluate(element => getComputedStyle(element).color);
    await expect(tabIcon).toHaveCSS('color', explicit);
    await ensureTabsOpen(page);
    await tab.click({ button: 'right' });
    await page.getByTestId('tab-icon-color-auto').click();
    await expect(tabIcon).toHaveCSS('color', inherited);
    await page.screenshot({ path: testInfo.outputPath('ssh-connection-colors.png'), animations: 'disabled' });
    await page.reload();
    if (!(await connection.isVisible())) await page.locator('[data-dock-btn="ssh"]').click();
    await expect(connectionIcon).toHaveCSS('color', inherited);
    await connection.dblclick();
    await ensureTabsOpen(page);
    await expect(tabIcon).toHaveCSS('color', inherited);
    await page.locator('[data-dock-btn="ssh"]').click();
    await connection.click({ button: 'right' });
    await page.getByTestId('ssh-icon-color-auto').click();
    await expect(connectionIcon).toHaveCSS('color', original);
    await expect(tabIcon).toHaveCSS('color', original);
  });
}
