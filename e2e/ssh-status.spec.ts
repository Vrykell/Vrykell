test('dragging the status edge folds the panel and releasing below the minimum closes it', async ({ page }) => {
  await setupTauriMock(page);
  await page.goto('/');
  await page.locator('[data-dock-btn="ssh"]').click();
  await page.getByTestId('ssh-row-ssh-1').dblclick();
  const toggle = page.getByTestId('ssh-status-toggle').last();
  await toggle.click();
  const panel = page.getByTestId('ssh-status-panel');
  await expect(panel).toBeVisible();
  expect(Math.round((await panel.boundingBox())!.width)).toBe(300);
  const start = (await page.getByTestId('ssh-status-resize-handle').boundingBox())!;
  const edgeX = start.x + start.width / 2;
  const y = start.y + 120;
  // Shrinking past the 240 px minimum folds the panel while its edge stays draggable.
  await page.mouse.move(edgeX, y);
  await page.mouse.down();
  await page.mouse.move(edgeX + 120, y, { steps: 6 });
  await expect(panel).toBeHidden();
  await expect(page.getByTestId('ssh-status-resize-handle')).toBeVisible();
  // Dragging back out restores it before the button is released.
  await page.mouse.move(edgeX + 80, y, { steps: 6 });
  await expect(panel).toBeVisible();
  await expect.poll(async () => Math.round((await panel.boundingBox())!.width)).toBe(280);
  await page.mouse.up();
  await expect(panel).toBeVisible();
  // Releasing at the minimum closes the panel, focuses the entry and keeps the width for reopening.
  const again = (await page.getByTestId('ssh-status-resize-handle').boundingBox())!;
  const againX = again.x + again.width / 2;
  await page.mouse.move(againX, y);
  await page.mouse.down();
  await page.mouse.move(againX + 200, y, { steps: 6 });
  await page.mouse.up();
  await expect(panel).toHaveCount(0);
  await expect(toggle).toBeFocused();
  await toggle.click();
  await expect.poll(async () => Math.round((await panel.boundingBox())!.width)).toBe(280);
});

